// Generates src/gen1/symbols.ts and src/gen1/maps.ts from pret's disassembly
// symbol files and constants (vendor-data/, fetched separately).
//   node tools/gen-gen1-data.ts

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const V = join(import.meta.dirname, '..', 'vendor-data');
const OUT = join(import.meta.dirname, '..', 'src', 'gen1');

const WRAM = [
  'wIsInBattle', 'wCurMap', 'wPartyCount', 'wPartySpecies', 'wPartyMons', 'wPartyMonOT', 'wPartyMonNicks',
  'wEnemyMonSpecies', 'wEnemyMonHP', 'wEnemyMonLevel', 'wEnemyMonDVs', 'wEnemyMonNick', 'wEnemyMonSpecies2',
  'wEnemyMonMaxHP', 'wBattleMon', 'wBattleMonHP', 'wBattleMonNick', 'wPlayerMonNumber', 'wBoxCount',
  'wBoxSpecies', 'wBoxMons', 'wBoxMonOT', 'wBoxMonNicks', 'wObtainedBadges', 'wPlayerName', 'wPlayerID',
  'wPokedexOwned', 'wPokedexSeen', 'wCurOpponent', 'wTrainerClass', 'wTrainerNo', 'wGymLeaderNo',
  'wBattleType', 'wCurrentBoxNum', 'wPlayerMoney', 'wEnemyPartyCount', 'wEnemyMons', 'wGrassRate', 'wGrassMons', 'wWaterRate', 'wWaterMons', 'wPlayTimeHours', 'wPlayTimeMinutes',
  'wPlayTimeSeconds', 'wNumBagItems', 'wBagItems', 'wCapturedMonSpecies', 'wNumSafariBalls', 'wXCoord',
  'wYCoord', 'wLinkState', 'wOptions', 'wStatusFlags5', 'wStatusFlags6', 'wEventFlags', 'wLastMap',
  'wRepelRemainingSteps',
  // Auto-grind: menu state, screen tiles and the active Pokémon's PP.
  'wTopMenuItemY', 'wTopMenuItemX', 'wCurrentMenuItem', 'wMaxMenuItem', 'wListScrollOffset', 'wTileMap',
  'wGrassTile', 'wBattleMonPP',
];
// Routines the auto-grind bot looks for on the game's call stack, emitted as
// [bank, start, end) ranges. Bankswitch and Predef push the caller's bank.
const ROUTINES = [
  'Bankswitch', 'Predef', 'OverworldLoop', 'OverworldLoopLessDelay', 'HandleMenuInput_', 'DisplayBattleMenu',
  'SelectMenuItem', 'MoveSelectionMenu', 'DisplayTwoOptionMenu', 'WaitForTextScrollButtonPress',
  'ManualTextScroll', 'DontAbandonLearning', 'TryingToLearn', 'AbandonLearning', 'EvolveMon', 'Evolution_PartyMonLoop',
  'HandlePartyMenuInput', 'DisplayStartMenu', 'RedisplayStartMenu', 'DisplayListMenuIDLoop',
  'DisplayChooseQuantityMenu', 'StartMenu_Item', 'ItemMenuLoop', 'HandlePlayerMonFainted', 'ChooseNextMon',
  'DisplayTextID',
];
const ROM = [
  'MonsterNames', 'PokedexOrder', 'BaseStats', 'MewBaseStats', 'WildDataPointers', 'MoveNames', 'Moves',
  'TypeEffects', 'EvosMovesPointerTable', 'TrainerDataPointers', 'TrainerNames', 'ItemNames', 'MewPicFront',
  'FossilKabutopsPic', 'FossilAerodactylPic', 'GhostPic', 'GoodRodMons', 'ReadSuperRodData', 'SuperRodData',
  'UncompressSpriteData',
];
const SRAM = ['sPlayerName', 'sMainData', 'sPartyData', 'sCurBoxData', 'sBox1', 'sBox7'];
// Pic bank by section, keyed by a pic known to live in each section.
const PIC_SECTIONS = ['TangelaPicFront', 'MoltresPicFront', 'BeedrillPicFront', 'StarmiePicFront', 'VictreebelPicFront'];

function parseSym(file: string): Map<string, { bank: number; addr: number }> {
  const m = new Map<string, { bank: number; addr: number }>();
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const r = /^([0-9a-f]{2}):([0-9a-f]{4}) (\S+)$/.exec(line.trim());
    if (r) m.set(r[3], { bank: parseInt(r[1], 16), addr: parseInt(r[2], 16) });
  }
  return m;
}

/** Global (non-local) ROM labels per bank, sorted, for routine end addresses. */
function routineRanges(file: string): Map<string, [number, number, number]> {
  const labels: { bank: number; addr: number; name: string }[] = [];
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const r = /^([0-9a-f]{2}):([0-9a-f]{4}) (\S+)$/.exec(line.trim());
    if (r && !r[3].includes('.') && parseInt(r[2], 16) < 0x8000) labels.push({ bank: parseInt(r[1], 16), addr: parseInt(r[2], 16), name: r[3] });
  }
  labels.sort((a, b) => a.bank - b.bank || a.addr - b.addr);
  const out = new Map<string, [number, number, number]>();
  labels.forEach((l, i) => {
    const next = labels.slice(i + 1).find((n) => n.bank === l.bank && n.addr > l.addr);
    out.set(l.name, [l.bank, l.addr, next ? next.addr : l.bank === 0 ? 0x4000 : 0x8000]);
  });
  return out;
}

function romOffset(s: { bank: number; addr: number }): number {
  return s.bank === 0 ? s.addr : s.bank * 0x4000 + (s.addr - 0x4000);
}

const versions = {
  red: join(V, 'pokered/pokered.sym'),
  blue: join(V, 'pokered/pokeblue.sym'),
  yellow: join(V, 'pokeyellow/pokeyellow.sym'),
};

let out = '// GENERATED by tools/gen-gen1-data.ts from pret disassembly symbols. Do not edit.\n\n';
out += 'export interface Gen1Symbols {\n';
for (const n of WRAM) out += `  ${n}: number;\n`;
for (const n of ROM) out += `  ${n}: number; // flat ROM offset (-1 if absent)\n`;
for (const n of SRAM) out += `  ${n}: number; // flat SRAM offset\n`;
out += '  picBanks: number[]; // bank per pic section 1..5\n';
out += '  /** Routine address ranges for the auto-grind bot: name -> [bank, start, end). */\n';
out += '  routines: Record<string, [number, number, number]>;\n';
out += '}\n\n';
out += 'export const SYMBOLS: Record<"red" | "blue" | "yellow", Gen1Symbols> = {\n';
for (const [ver, file] of Object.entries(versions)) {
  const sym = parseSym(file);
  out += `  ${ver}: {\n`;
  for (const n of WRAM) {
    const s = sym.get(n);
    if (!s) throw new Error(`${ver}: missing ${n}`);
    out += `    ${n}: 0x${s.addr.toString(16)},\n`;
  }
  for (const n of ROM) {
    const s = sym.get(n);
    out += `    ${n}: ${s ? '0x' + romOffset(s).toString(16) : -1},\n`;
  }
  for (const n of SRAM) {
    const s = sym.get(n);
    if (!s) throw new Error(`${ver}: missing ${n}`);
    out += `    ${n}: 0x${(s.bank * 0x2000 + (s.addr - 0xa000)).toString(16)},\n`;
  }
  const banks = PIC_SECTIONS.map((p) => {
    const s = sym.get(p);
    if (!s) throw new Error(`${ver}: missing ${p}`);
    return s.bank;
  });
  out += `    picBanks: [${banks.join(', ')}],\n`;
  const ranges = routineRanges(file);
  out += '    routines: {\n';
  for (const n of ROUTINES) {
    const r = ranges.get(n);
    if (!r) throw new Error(`${ver}: missing routine ${n}`);
    out += `      ${n}: [0x${r[0].toString(16)}, 0x${r[1].toString(16)}, 0x${r[2].toString(16)}],\n`;
  }
  out += '    },\n';
  out += '  },\n';
}
out += '};\n';
writeFileSync(join(OUT, 'symbols.ts'), out);

// ---- Maps ----
const mapSrc = readFileSync(join(V, 'pokered/constants/map_constants.asm'), 'utf8');
const maps: string[] = [];
for (const line of mapSrc.split('\n')) {
  const r = /^\s*map_const\s+([A-Z0-9_]+),/.exec(line);
  if (r) maps.push(r[1]);
}

const SPECIAL: Record<string, string> = {
  SS_ANNE: 'S.S. Anne',
  MT_MOON: 'Mt. Moon',
  POKEMON_TOWER: 'Pokémon Tower',
  POKEMON_MANSION: 'Pokémon Mansion',
  POKEMON_FAN_CLUB: 'Pokémon Fan Club',
  SILPH_CO: 'Silph Co.',
  DIGLETTS_CAVE: "Diglett's Cave",
  ROCKET_HIDEOUT: 'Rocket Hideout',
  SEAFOAM_ISLANDS: 'Seafoam Islands',
  VICTORY_ROAD: 'Victory Road',
  CERULEAN_CAVE: 'Cerulean Cave',
  ROCK_TUNNEL: 'Rock Tunnel',
  SAFARI_ZONE: 'Safari Zone',
  POWER_PLANT: 'Power Plant',
  VIRIDIAN_FOREST: 'Viridian Forest',
  UNDERGROUND_PATH: 'Underground Path',
};
// Areas that group several maps for the "one encounter per area" rule.
const AREA_PREFIXES = Object.keys(SPECIAL).sort((a, b) => b.length - a.length);

function titleCase(s: string): string {
  return s
    .split('_')
    .map((w) => {
      if (/^B?\d+F$/.test(w) || /^\d+F$/.test(w)) return w;
      if (/^\d+$/.test(w)) return w;
      const words: Record<string, string> = {
        SS: 'S.S.', REDS: "Red's", BLUES: "Blue's", OAKS: "Oak's", POKECENTER: 'Pokémon Center',
        MART: 'Poké Mart', OF: 'of', BILLS: "Bill's", COPYCATS: "Copycat's", MR: 'Mr.', PSYCHICS: "Psychic's",
        FUJIS: "Fuji's", RATERS: "Rater's", DIGLETTS: "Diglett's",
      };
      if (words[w]) return words[w];
      if (w === 'MT') return 'Mt.';
      if (w === 'PEWTER' || w === 'PALLET') return w[0] + w.slice(1).toLowerCase();
      return w[0] + w.slice(1).toLowerCase();
    })
    .join(' ');
}

function nameFor(c: string): { name: string; area: string } {
  for (const p of AREA_PREFIXES) {
    if (c === p || c.startsWith(p + '_')) {
      const rest = c.slice(p.length + 1);
      const area = SPECIAL[p];
      return { name: rest ? `${area} ${titleCase(rest)}` : area, area };
    }
  }
  const route = /^ROUTE_(\d+)(?:_(.*))?$/.exec(c);
  if (route) {
    const area = `Route ${route[1]}`;
    return { name: route[2] ? `${area} ${titleCase(route[2])}` : area, area };
  }
  const n = titleCase(c);
  if (/^(REDS_HOUSE|BLUES_HOUSE|OAKS_LAB)/.test(c)) return { name: n, area: 'Pallet Town' };
  // Towns: group buildings under the town name (e.g. CELADON_MANSION_1F -> Celadon City).
  const town = /^(PALLET_TOWN|VIRIDIAN_CITY|PEWTER_CITY|CERULEAN_CITY|LAVENDER_TOWN|VERMILION_CITY|CELADON_CITY|FUCHSIA_CITY|CINNABAR_ISLAND|INDIGO_PLATEAU|SAFFRON_CITY)$/.exec(c);
  if (town) return { name: n, area: n };
  const townPrefix = /^(VIRIDIAN|PEWTER|CERULEAN|LAVENDER|VERMILION|CELADON|FUCHSIA|CINNABAR|SAFFRON|PALLET|INDIGO)_/.exec(c);
  if (townPrefix) {
    const t = townPrefix[1];
    const suffix: Record<string, string> = {
      PALLET: 'Pallet Town', LAVENDER: 'Lavender Town', CINNABAR: 'Cinnabar Island', INDIGO: 'Indigo Plateau',
    };
    return { name: n, area: suffix[t] ?? `${t[0]}${t.slice(1).toLowerCase()} City` };
  }
  return { name: n, area: n };
}

let mo = '// GENERATED by tools/gen-gen1-data.ts from pret map constants. Do not edit.\n\n';
mo += 'export interface MapInfo {\n  id: number;\n  const: string;\n  name: string;\n  area: string;\n}\n\n';
mo += 'export const MAPS: MapInfo[] = [\n';
maps.forEach((c, id) => {
  const { name, area } = nameFor(c);
  mo += `  { id: ${id}, const: ${JSON.stringify(c)}, name: ${JSON.stringify(name)}, area: ${JSON.stringify(area)} },\n`;
});
mo += '];\n';
writeFileSync(join(OUT, 'maps.ts'), mo);
console.log(`wrote symbols for ${Object.keys(versions).length} versions, ${maps.length} maps`);
